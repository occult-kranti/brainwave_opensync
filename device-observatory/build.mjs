import { cp, mkdir, rm, readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { sources } from './src/sources.mjs';
import { devices } from './src/catalog.mjs';
import { deviceModels } from './src/models.mjs';
const root = fileURLToPath(new URL('.', import.meta.url));
const out = join(root, 'dist');
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await cp(join(root, 'index.html'), join(out, 'index.html'));
await cp(join(root, 'src'), join(out, 'src'), { recursive: true });
await cp(join(root, 'public'), out, { recursive: true });
await cp(join(root, 'research'), join(out, 'research'), { recursive: true });
await cp(join(root, 'tests'), join(out, 'code/tests'), { recursive: true });
await cp(join(root, 'src'), join(out, 'code/src'), { recursive: true });
await writeFile(join(out, 'code/package.json'), JSON.stringify({ name:'fieldwork-model-source',type:'module',private:true,scripts:{test:'node --test tests/*.test.mjs'} },null,2)+'\n');
await cp(join(root, '../LICENSE'), join(out, 'LICENSE'));
const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
const buildInfo = `export const BUILD_INFO = ${JSON.stringify({modelVersion:'1.0.0',researchDate:'2026-10-16',sourceCommit:commit,branch:'research/device-observatory'})};\n`;
await writeFile(join(out,'src/build-info.mjs'),buildInfo);
await writeFile(join(out,'code/src/build-info.mjs'),buildInfo);
const evidence = { schemaVersion: 1, asOf: '2026-10-16', scope: 'Selected public primary sources; not exhaustive, and no hardware replication.', sources, devices };
await writeFile(join(out, 'research/evidence.json'), JSON.stringify(evidence, null, 2) + '\n');
const reports = ['ai-frontier.md','historical-devices.md','model-specification.md','independent-review.md','integration-checks.md','image-provenance.md'];
const chapters = await Promise.all(reports.map(async (file) => `\n\n---\n\n<!-- ${file} -->\n\n${await readFile(join(root, 'research', file), 'utf8')}`));
await writeFile(join(out, 'research/device-observatory-dossier.md'), '# Fieldwork: Device Observatory\n\nResearch snapshot: 16 October 2026. Selected primary sources, three virtual instruments, and proposed experiments. No physical prototype was built or measured.\n\n'+chapters.join(''));
await writeFile(join(out, 'deployment.json'), JSON.stringify({ site: 'Fieldwork / Device Observatory', branch: 'research/device-observatory', commit, path: '/brainwave_opensync/devices/', asOf: '2026-10-16', modelCount: devices.length, hypothesisCount: devices.reduce((n,d)=>n+d.hypotheses.length,0), presetCount: Object.values(deviceModels).reduce((n,m)=>n+m.presets.length,0), sourceCount: sources.length, runtimeDependencies: 0 }, null, 2)+'\n');
await writeFile(join(out, '.nojekyll'), '');
console.log(`Built ${devices.length} virtual devices and ${sources.length} source records for /devices/.`);
